"""
pages/tutor.py — AI Tutor page.

Students enter a subject, topic, and learning level to receive a plain-language
explanation with concrete examples, generated by the LLM adapter.

In demo mode (no API key) the explanation is drawn from bundled sample content
and a clearly visible warning badge is shown so students know it is not
AI-generated.
"""

from __future__ import annotations

import streamlit as st

from learnmate_ai import llm_adapter
from learnmate_ai.pages.profile import LEARNING_LEVELS


def render() -> None:
    """Render the AI Tutor page."""
    st.title("🤖 AI Tutor")
    st.write(
        "Enter a subject and topic below to receive a clear explanation "
        "tailored to your learning level, with examples."
    )

    # ── Demo mode badge (shown before any interaction) ───────────────────────
    if llm_adapter.is_demo_mode():
        st.warning(
            "⚠️ **Demo Mode** — No API key is configured. "
            "Explanations below are pre-written sample content, **not** AI-generated.",
            icon="⚠️",
        )

    # ── Input form ───────────────────────────────────────────────────────────
    with st.form("tutor_form"):
        col1, col2 = st.columns(2)

        with col1:
            subject = st.text_input(
                "Subject",
                placeholder="e.g. Mathematics",
                help="The broad subject area (e.g. Mathematics, Science, History).",
            )

        with col2:
            topic = st.text_input(
                "Topic",
                placeholder="e.g. Algebra",
                help="The specific topic you want explained.",
            )

        # Pre-fill level from profile; allow per-request override.
        current_level = st.session_state.get("learning_level", LEARNING_LEVELS[0])
        try:
            level_index = LEARNING_LEVELS.index(current_level)
        except ValueError:
            level_index = 0

        level = st.selectbox(
            "Learning Level",
            options=LEARNING_LEVELS,
            index=level_index,
            help="Override your profile level for this explanation if needed.",
        )

        submitted = st.form_submit_button("✨ Explain This Topic", use_container_width=True)

    # ── Validation + LLM call ────────────────────────────────────────────────
    if submitted:
        subject_clean = subject.strip()
        topic_clean   = topic.strip()

        if not subject_clean:
            st.error("⚠️ Please enter a subject.")
        elif not topic_clean:
            st.error("⚠️ Please enter a topic.")
        else:
            with st.spinner(f"Generating explanation for **{topic_clean}** in **{subject_clean}**…"):
                try:
                    explanation = llm_adapter.explain_topic(subject_clean, topic_clean, level)
                except llm_adapter.LLMError as exc:
                    st.error(
                        f"❌ Could not generate an explanation. "
                        f"Please check your API configuration and try again.\n\n"
                        f"*Details: {exc}*"
                    )
                    return

            # ── Render explanation card ───────────────────────────────────
            st.divider()
            st.subheader(f"📖 {topic_clean} — {subject_clean} ({level})")

            # Demo badge repeated inline so it is always adjacent to the content.
            if llm_adapter.is_demo_mode():
                st.warning(
                    "📚 **Demo Mode — Sample Content.** "
                    "This explanation is pre-written and not AI-generated.",
                    icon="📚",
                )

            st.markdown(explanation)
