"""
pages/quiz.py — Smart Quiz Generator & Inline Feedback page.

Flow
────
1. Generation form   — student picks subject / topic / difficulty / n.
2. Question display  — all questions shown at once, one st.radio per question.
3. Submission        — evaluate_quiz(), inline feedback, summary banner, DB save.
4. New Quiz button   — clears ALL quiz + answer widget state, returns to form.

Session-state keys managed here
────────────────────────────────
  current_quiz          list[dict]   Generated MCQ dicts (question/options/answer).
  quiz_subject          str
  quiz_topic            str
  quiz_difficulty       str
  quiz_level            str          Learning level used when quiz was generated.
  quiz_submitted        bool         True once the student has clicked Submit.
  quiz_result           dict | None  Output of evaluate_quiz() after submission.
  quiz_attempt_id       int | None   DB id from save_quiz_attempt(); persisted
                                     before save_question_responses() is called.
                                     On rerun after a failed response-save, Step A
                                     is skipped (attempt already exists) and only
                                     Step B is retried — no duplicate attempt rows.
  quiz_responses_saved  bool         True once save_question_responses() succeeded.

Answer keys  answer_1 … answer_10  are cleared by the "New Quiz" on_click callback
*before* Streamlit re-renders, so old selections never bleed into the next quiz.
"""

from __future__ import annotations

import streamlit as st

from learnmate_ai import database, llm_adapter, quiz_engine
from learnmate_ai.pages.profile import LEARNING_LEVELS

# ── Constants ─────────────────────────────────────────────────────────────────
DIFFICULTIES: list[str] = ["easy", "medium", "hard"]
_MIN_Q = 3
_MAX_Q = 10
_DEFAULT_Q = 5

# All non-answer session-state keys owned by this page.
_QUIZ_META_KEYS = (
    "current_quiz", "quiz_subject", "quiz_topic", "quiz_difficulty",
    "quiz_level", "quiz_submitted", "quiz_result",
    "quiz_attempt_id", "quiz_responses_saved",
    "_submit_warned",
)


def _answer_key(i: int) -> str:
    """Session-state key for the i-th answer radio widget (1-based)."""
    return f"answer_{i}"


def _reset_quiz_callback() -> None:
    """on_click callback: clear all quiz metadata AND every answer widget key.

    Streamlit fires on_click callbacks *before* re-running the script, so
    widget keys popped here are gone by the time the new render starts.
    This is the only safe place to pop keyed-widget state mid-session.
    """
    for key in _QUIZ_META_KEYS:
        st.session_state.pop(key, None)
    # Sweep the full possible range so shorter follow-up quizzes never
    # inherit selections from a longer previous quiz.
    for i in range(1, _MAX_Q + 1):
        st.session_state.pop(_answer_key(i), None)


def _has_profile() -> bool:
    return "student_id" in st.session_state


def _profile_prompt() -> None:
    st.warning(
        "Please complete your **Student Profile** before taking a quiz. "
        "Your results will be saved against your profile.",
        icon="⚠️",
    )


# ── Main render ───────────────────────────────────────────────────────────────

def render() -> None:
    """Render the Smart Quiz Generator page."""
    st.title("Smart Quiz Generator")

    if not _has_profile():
        _profile_prompt()
        return

    if llm_adapter.is_demo_mode():
        st.info(
            "Demo Mode — Questions are drawn from bundled sample data, "
            "not generated by AI.",
            icon="📚",
        )

    quiz_ready = "current_quiz" in st.session_state
    submitted  = st.session_state.get("quiz_submitted", False)

    if not quiz_ready:
        _render_generation_form()
        return

    questions = st.session_state["current_quiz"]

    if not questions:
        st.error(
            "No questions were returned for the selected subject / difficulty. "
            "Try a different combination."
        )
        st.button("Back to Quiz Setup", on_click=_reset_quiz_callback)
        return

    st.write(
        f"**Subject:** {st.session_state.quiz_subject}  |  "
        f"**Topic:** {st.session_state.quiz_topic}  |  "
        f"**Difficulty:** {st.session_state.quiz_difficulty.capitalize()}  |  "
        f"**Questions:** {len(questions)}"
    )

    if not submitted:
        _render_questions(questions)
    else:
        _render_feedback(questions)


# ── Phase 1: generation form ──────────────────────────────────────────────────

def _render_generation_form() -> None:
    current_level = st.session_state.get("learning_level", LEARNING_LEVELS[0])

    with st.form("quiz_gen_form"):
        col1, col2 = st.columns(2)

        with col1:
            subject = st.text_input(
                "Subject",
                placeholder="e.g. Mathematics",
            )
            difficulty = st.selectbox(
                "Difficulty",
                options=DIFFICULTIES,
                format_func=str.capitalize,
            )

        with col2:
            topic = st.text_input(
                "Topic",
                placeholder="e.g. Algebra",
            )
            try:
                level_idx = LEARNING_LEVELS.index(current_level)
            except ValueError:
                level_idx = 0
            level = st.selectbox(
                "Learning Level",
                options=LEARNING_LEVELS,
                index=level_idx,
            )

        n_questions = st.slider(
            "Number of Questions",
            min_value=_MIN_Q,
            max_value=_MAX_Q,
            value=_DEFAULT_Q,
        )

        generate_clicked = st.form_submit_button(
            "Generate Quiz", use_container_width=True
        )

    if generate_clicked:
        subject_clean = subject.strip()
        topic_clean   = topic.strip()

        if not subject_clean:
            st.error("Please enter a subject.")
            return
        if not topic_clean:
            st.error("Please enter a topic.")
            return

        with st.spinner("Generating quiz questions…"):
            try:
                questions = llm_adapter.generate_quiz(
                    subject_clean, topic_clean, level, difficulty, n_questions
                )
            except llm_adapter.LLMError as exc:
                st.error(f"Could not generate questions. Details: {exc}")
                return
            except Exception as exc:
                st.error(f"An unexpected error occurred: {exc}")
                return

        if not questions:
            st.warning(
                "No questions were found for that combination. "
                "Try a different subject or difficulty."
            )
            return

        # Clear any stale answer keys before storing new quiz
        for i in range(1, _MAX_Q + 1):
            st.session_state.pop(_answer_key(i), None)

        st.session_state.current_quiz         = questions
        st.session_state.quiz_subject         = subject_clean
        st.session_state.quiz_topic           = topic_clean
        st.session_state.quiz_difficulty      = difficulty
        st.session_state.quiz_level           = level
        st.session_state.quiz_submitted       = False
        st.session_state.quiz_result          = None
        st.session_state.quiz_attempt_id      = None
        st.session_state.quiz_responses_saved = False
        st.rerun()


# ── Phase 2: question display ─────────────────────────────────────────────────

def _render_questions(questions: list[dict]) -> None:
    st.subheader("Answer All Questions")
    st.caption("Select one answer per question, then click **Submit Quiz**.")

    for i, q in enumerate(questions, start=1):
        st.markdown(f"**Q{i}.** {q['question']}")
        st.radio(
            label=f"q_{i}",
            options=q["options"],
            index=None,
            key=_answer_key(i),
            label_visibility="collapsed",
        )
        st.divider()

    col_submit, col_reset = st.columns([3, 1])
    with col_submit:
        submit_clicked = st.button(
            "Submit Quiz", use_container_width=True, type="primary"
        )
    with col_reset:
        # on_click fires before re-render: widget keys are gone when page reloads.
        st.button("New Quiz", use_container_width=True, on_click=_reset_quiz_callback)

    if submit_clicked:
        student_answers = [
            st.session_state.get(_answer_key(i))
            for i in range(1, len(questions) + 1)
        ]

        unanswered = [i + 1 for i, a in enumerate(student_answers) if a is None]
        if unanswered and not st.session_state.get("_submit_warned"):
            nums = ", ".join(f"Q{n}" for n in unanswered)
            st.warning(
                f"You have not answered {nums}. "
                "Unanswered questions will be marked incorrect. "
                "Click Submit Quiz again to confirm."
            )
            st.session_state["_submit_warned"] = True
            return

        st.session_state.pop("_submit_warned", None)

        result = quiz_engine.evaluate_quiz(questions, student_answers)
        st.session_state.quiz_result          = result
        st.session_state.quiz_submitted       = True
        st.session_state.quiz_attempt_id      = None
        st.session_state.quiz_responses_saved = False
        st.rerun()


# ── Phase 3: feedback + resilient persistence ─────────────────────────────────

def _render_feedback(questions: list[dict]) -> None:
    """Show results and save to DB in two guarded steps.

    Step A — save_quiz_attempt():
        Runs only when quiz_attempt_id is None.
        On success, quiz_attempt_id is written to session state immediately.
        On failure, an error is shown and we return early.

    Step B — save_question_responses():
        Runs only when quiz_attempt_id is set AND quiz_responses_saved is False.
        Uses a single executemany inside a transaction (atomic rollback on error).
        On failure, quiz_responses_saved stays False so the next rerun retries
        Step B only — no second attempt row is ever created.
    """
    result = st.session_state.get("quiz_result") or {}
    per_q  = result.get("per_question", [])
    score  = result.get("score", 0)
    total  = result.get("total", len(questions))
    acc    = result.get("accuracy", 0.0)

    # ── Summary banner ────────────────────────────────────────────────────────
    acc_pct = round(acc * 100, 1)
    if acc >= 0.8:
        banner_fn, label = st.success, "Great work!"
    elif acc >= 0.6:
        banner_fn, label = st.info, "Good effort!"
    else:
        banner_fn, label = st.warning, "Keep practising!"

    banner_fn(
        f"**Quiz Complete — {label}** "
        f"Score: **{score} / {total}** — Accuracy: **{acc_pct}%**"
    )

    # ── Per-question inline feedback ─────────────────────────────────────────
    st.subheader("Question Feedback")
    for i, pq in enumerate(per_q, start=1):
        result_label = "Correct" if pq["is_correct"] else "Incorrect"
        student_ans  = pq["student_answer"] if pq["student_answer"] else "Not answered"
        st.markdown(f"**Q{i}.** {pq['question']}")
        st.markdown(
            f"- Your answer: **{student_ans}** — *{result_label}*\n"
            f"- Correct answer: **{pq['correct_answer']}**"
        )
        st.divider()

    # ── Resilient two-step persistence ───────────────────────────────────────
    attempt_id      = st.session_state.get("quiz_attempt_id")
    responses_saved = st.session_state.get("quiz_responses_saved", False)

    if not responses_saved:
        # Step A: create the attempt row (idempotent — skipped if already done)
        if attempt_id is None:
            try:
                attempt_id = database.save_quiz_attempt(
                    student_id      = st.session_state.student_id,
                    subject         = st.session_state.quiz_subject,
                    topic           = st.session_state.quiz_topic,
                    difficulty      = st.session_state.quiz_difficulty,
                    score           = score,
                    total_questions = total,
                    accuracy        = acc,
                )
                # Persist ID immediately so a rerun skips Step A
                st.session_state.quiz_attempt_id = attempt_id
            except Exception as exc:
                st.error(f"Could not save quiz attempt: {exc}")
                st.button("New Quiz", on_click=_reset_quiz_callback)
                return

        # Step B: save responses (atomic; retry-safe because executemany is
        # wrapped in a transaction that fully rolls back on any failure)
        responses = [
            {
                "question_text":  pq["question"],
                "correct_answer": pq["correct_answer"],
                "student_answer": pq["student_answer"],
                "is_correct":     int(pq["is_correct"]),
            }
            for pq in per_q
        ]
        try:
            database.save_question_responses(attempt_id, responses)
            st.session_state.quiz_responses_saved = True
        except Exception as exc:
            st.error(
                f"Quiz score was recorded (attempt #{attempt_id}), but "
                f"individual responses could not be saved: {exc}\n\n"
                "Reload the page to retry."
            )

    # ── New Quiz button ───────────────────────────────────────────────────────
    st.divider()
    st.button(
        "Start a New Quiz",
        use_container_width=True,
        on_click=_reset_quiz_callback,
    )
